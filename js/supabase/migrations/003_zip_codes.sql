-- ZIP code checker: which ZIPs map to which delivery city
create table public.zip_codes (
  zip text primary key check (zip ~ '^[0-9]{5}$'),
  city text not null
);
alter table public.zip_codes enable row level security;
create policy "public read" on public.zip_codes for select to anon, authenticated using (true);
create policy "admin insert" on public.zip_codes for insert to authenticated with check ((select public.is_admin()));
create policy "admin update" on public.zip_codes for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "admin remove" on public.zip_codes for delete to authenticated using ((select public.is_admin()));
